def main() -> int:
    if sys.platform == "win32":
        try:
            sys.stdout.reconfigure(encoding="utf-8")
        except Exception:
            pass

    source = DEFAULT_SOURCE
    problems: list[str] = []
    rows: list[dict] = []

    print(f"{'id':<7} {'kind':<8} {'verdict':<8} {'score':>5}  fmt     salary  notes")
    print("-" * 100)
    for post in REAL_POSTS:
        decision = is_vacancy(post["text"], source=source)
        work_format = detect_work_format(post["text"])
        salary = extract_salary(post["text"])
        rotation = extract_rotation(post["text"])
        location = extract_work_location(post["text"])
        salary_s = "—"
        if salary is not None:
            salary_s = f"{salary.min_amount or '—'}-{salary.max_amount or '—'}"
        print(
            f"{post['id']:<7} {post['kind']:<8} {decision.verdict:<8} {decision.score:>5}  "
            f"{work_format:<7} {salary_s:<12} {decision.reasons[:3]}"
        )
        if post["kind"] == "vacancy" and decision.verdict == "reject":
            problems.append(f"{post['id']} вакансия от Broшена: {decision.score} {decision.reasons}")
        if post["kind"] == "junk" and decision.verdict == "accept":
            problems.append(f"{post['id']} мусор принят: {decision.score} {decision.reasons}")
        if post["kind"] == "maybe" and decision.verdict == "reject":
            problems.append(f"{post['id']} спорное потеряно: {decision.score} {decision.reasons}")
        if post["id"].startswith("rva") and work_format != "VAHTA":
            problems.append(f"{post['id']} не вахта: {work_format}")
        expected = decision.verdict
        if post["kind"] == "junk":
            expected = "reject"
        elif post["kind"] == "maybe" and decision.verdict == "accept":
            expected = "accept"
        row = {
            "id": post["id"],
            "kind": post["kind"],
            "expected": expected,
            "origin": "real",
            "text": post["text"],
        }
        if rotation:
            row["_rotation"] = rotation.pattern
        if location.work_destination_slug or location.work_city_slug:
            row["_work"] = location.work_destination_slug or location.work_city_slug
        rows.append(row)

    data = json.loads(FIXTURES.read_text(encoding="utf-8"))
    kept = [item for item in data["posts"] if item.get("origin") != "real"]
    clean_rows = []
    for row in rows:
        clean_rows.append(
            {
                "id": row["id"],
                "kind": row["kind"],
                "expected": row["expected"],
                "origin": "real",
                "text": row["text"],
            }
        )
    data["posts"] = kept + clean_rows
    FIXTURES.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print()
    print(f"Записано живых постов: {len(clean_rows)}, синтетика: {len(kept)}")
    if problems:
        print("ПРОБЛЕМЫ:")
        for line in problems:
            print(" ", line)
        return 1
    print("Политика части 1 на живых постах соблюдена.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
